import assert from 'node:assert/strict';
import { mkdtemp, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import test from 'node:test';
import { assertTranscript, type Transcript } from '../../shared/transcript';
import { createPilaServer } from '../index';

const VIDEO_ID = '7wFWgopJP5Q';
const VIDEO_URL = `https://www.youtube.com/watch?v=${VIDEO_ID}`;
const transcript: Transcript = {
  videoId: VIDEO_ID,
  sentences: [{ id: 's0001', text: '這是一句話。', start: 1, end: 3 }],
};
type Dependencies = Omit<Parameters<typeof createPilaServer>[0], 'outputDirectory'>;

async function withServer(
  dependencies: Dependencies,
  run: (url: string, directory: string) => Promise<void>,
) {
  const directory = await mkdtemp(join(tmpdir(), 'pila-server-'));
  const server = createPilaServer({
    outputDirectory: directory,
    extract: async () => structuredClone(transcript),
    languages: async () => [{ languageCode: 'zh-TW', languageName: 'Chinese (Taiwan)', isAutoGenerated: false }],
    ...dependencies,
  });
  try {
    await new Promise<void>((resolve, reject) => {
      server.once('error', reject);
      server.listen(0, '127.0.0.1', resolve);
    });
    const address = server.address();
    assert(address && typeof address !== 'string');
    await run(`http://127.0.0.1:${address.port}`, directory);
  } finally {
    server.closeAllConnections();
    if (server.listening) await new Promise<void>((resolve, reject) => server.close(error => error ? reject(error) : resolve()));
    await rm(directory, { recursive: true, force: true });
  }
}

function submit(base: string, body: unknown) {
  return fetch(`${base}/extract`, {
    method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body),
  });
}

test('a client sends only a YouTube URL and the server writes the JSON contract', async () => {
  await withServer({ extract: async (input, options) => {
    assert.equal(input, VIDEO_URL);
    assert.equal(options?.lang, 'zh-TW');
    assert(options?.signal instanceof AbortSignal);
    return structuredClone(transcript);
  } }, async (base, directory) => {
    const response = await submit(base, { url: VIDEO_URL });
    assert.equal(response.status, 201);
    assert.deepEqual(await response.json(), {
      videoId: VIDEO_ID, language: 'zh-TW', file: join(directory, `${VIDEO_ID}.json`), sentenceCount: 1,
    });
    const saved: unknown = JSON.parse(await readFile(join(directory, `${VIDEO_ID}.json`), 'utf8'));
    assertTranscript(saved);
    assert.deepEqual(saved, transcript);
    assert.deepEqual(await readdir(directory), [`${VIDEO_ID}.json`]);
  });
});

test('an exact requested language is passed to Extract without choosing another track', async () => {
  await withServer({
    languages: async () => { throw new Error('Should not discover languages for an explicit track'); },
    extract: async (_input, options) => {
      assert.equal(options?.lang, 'zh-Hant');
      return structuredClone(transcript);
    },
  }, async (base) => {
    const response = await submit(base, { url: VIDEO_URL, lang: 'zh-Hant' });
    assert.equal(response.status, 201);
    const body: unknown = await response.json();
    assert(body !== null && typeof body === 'object' && 'language' in body);
    assert.equal(body.language, 'zh-Hant');
  });
});

test('an existing file returns 409 before contacting YouTube and remains unchanged', async () => {
  await withServer({
    extract: async () => { throw new Error('Should not extract'); },
    languages: async () => { throw new Error('Should not list languages'); },
  }, async (base, directory) => {
    const file = join(directory, `${VIDEO_ID}.json`);
    await writeFile(file, 'existing transcript', 'utf8');
    const response = await submit(base, { url: VIDEO_URL });
    assert.equal(response.status, 409);
    const body: unknown = await response.json();
    assert(body !== null && typeof body === 'object' && 'error' in body);
    assert(body.error !== null && typeof body.error === 'object' && 'code' in body.error);
    assert.equal(body.error.code, 'transcript_exists');
    assert.equal(await readFile(file, 'utf8'), 'existing transcript');
  });
});

test('concurrent requests create exactly one file without replacing each other', async () => {
  let calls = 0;
  let release!: () => void;
  const bothExtracting = new Promise<void>(resolve => { release = resolve; });
  await withServer({ extract: async () => {
    calls += 1;
    if (calls === 2) release();
    await bothExtracting;
    return structuredClone(transcript);
  } }, async (base, directory) => {
    const responses = await Promise.all([
      submit(base, { url: VIDEO_URL, lang: 'zh-TW' }),
      submit(base, { url: VIDEO_URL, lang: 'zh-TW' }),
    ]);
    assert.deepEqual(responses.map(response => response.status).sort(), [201, 409]);
    assert.deepEqual(JSON.parse(await readFile(join(directory, `${VIDEO_ID}.json`), 'utf8')), transcript);
    assert.deepEqual(await readdir(directory), [`${VIDEO_ID}.json`]);
  });
});

test('invalid requests cannot select an output path or start extraction', async () => {
  await withServer({ extract: async () => { throw new Error('Should not extract'); } }, async (base, directory) => {
    for (const body of [null, {}, { url: 'invalid' }, { url: VIDEO_URL, out: '/tmp/other.json' }, { url: VIDEO_URL, lang: 'bad_locale' }]) {
      const response = await submit(base, body);
      assert.equal(response.status, 400);
    }
    const malformed = await fetch(`${base}/extract`, {
      method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{',
    });
    assert.equal(malformed.status, 400);
    const oversized = await submit(base, { url: VIDEO_URL, lang: 'x'.repeat(17_000) });
    assert.equal(oversized.status, 413);
    const wrongType = await fetch(`${base}/extract`, { method: 'POST', body: VIDEO_URL });
    assert.equal(wrongType.status, 415);
    const wrongMethod = await fetch(`${base}/extract`);
    assert.equal(wrongMethod.status, 405);
    assert.equal(wrongMethod.headers.get('allow'), 'POST');
    assert.equal((await fetch(`${base}/missing`)).status, 404);
    assert.equal((await fetch(`${base}/health`)).status, 200);
    assert.deepEqual(await readdir(directory), []);
  });
});

test('missing captions and provider failures never create a transcript file', async () => {
  await withServer({ languages: async () => [] }, async (base, directory) => {
    assert.equal((await submit(base, { url: VIDEO_URL })).status, 422);
    assert.deepEqual(await readdir(directory), []);
  });
  await withServer({ extract: async () => { throw new Error('YouTube blocked retrieval'); } }, async (base, directory) => {
    assert.equal((await submit(base, { url: VIDEO_URL })).status, 502);
    assert.deepEqual(await readdir(directory), []);
  });
});
