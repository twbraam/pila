/**
 * The shared data contracts from the repo README: what Ingestion gives us (`Transcript`) and
 * what Processing returns to Overlay (`FactCheckResult`).
 */
import * as z from "zod/mini";
import { InvalidInputError } from "./errors.js";
import { detectLanguage, MAX_SENTENCE_CHARS, parseTranscript, pickLanguage, toTimedSentences } from "./transcript.js";
import type { Language, Sentence, TranscriptSegment } from "./types.js";

export interface SubtitleSentence {
  readonly id: string;
  readonly text: string;
  readonly startSeconds: number;
  readonly endSeconds: number;
}

export interface Transcript {
  readonly videoId: string;
  readonly sentences: readonly SubtitleSentence[];
}

export type FactCheckVerdict = "misinformation" | "verified" | "unknown";

export interface FactCheckResult {
  readonly videoId: string;
  readonly sentenceId: string;
  readonly startSeconds: number;
  readonly endSeconds: number;
  /** The sentence as given in the transcript. */
  readonly sentence: string;
  readonly verdict: FactCheckVerdict;
  /** 0-1. */
  readonly confidence: number;
  /** Built from a template and a quote from the best source; not generated by a model. */
  readonly explanation: string;
  /** Best first. Empty when nothing relevant was found. */
  readonly sources: ReadonlyArray<{ readonly title: string; readonly url: string }>;
}

const seconds = z.number().check(z.nonnegative());
/** About 30 hours of speech; more is not a real video. */
const MAX_SENTENCES = 10_000;
const transcriptSchema = z.object({
  videoId: z.string().check(z.minLength(1)),
  sentences: z
    .array(z.object({ id: z.string().check(z.minLength(1)), text: z.string(), startSeconds: seconds, endSeconds: seconds }))
    .check(z.minLength(1), z.maxLength(MAX_SENTENCES)),
});

/** Validate an untrusted `Transcript` from Ingestion. */
export function parseContractTranscript(input: unknown): Transcript {
  const result = transcriptSchema.safeParse(input);
  if (!result.success) throw new InvalidInputError(`Invalid transcript: ${z.prettifyError(result.error)}`);
  const { sentences } = result.data;
  const backwards = sentences.find((s) => s.endSeconds < s.startSeconds);
  if (backwards) throw new InvalidInputError(`Invalid transcript: sentence ${backwards.id} ends before it starts`);
  if (new Set(sentences.map((s) => s.id)).size !== sentences.length) {
    throw new InvalidInputError("Invalid transcript: sentence ids must be unique");
  }
  return result.data;
}

export const detectTranscriptLanguage = (transcript: Transcript): Language =>
  detectLanguage(transcript.sentences.map((s) => ({ text: s.text, start: s.startSeconds, duration: 0 })));

export interface PipelineSentence {
  readonly sentence: Sentence;
  readonly ref: SubtitleSentence;
}

/**
 * The text each sentence has in `language`, numbered for the pipeline, with the original kept.
 * Long sentences are cut to the same length the caption path allows.
 */
export function toPipelineSentences(transcript: Transcript, language: Language): PipelineSentence[] {
  return transcript.sentences
    .map((ref) => ({ ref, text: pickLanguage(ref.text, language).slice(0, MAX_SENTENCE_CHARS[language]) }))
    .filter((p) => p.text.length > 0)
    .map(({ ref, text }, index) => ({ ref, sentence: { index, start: ref.startSeconds, text } }));
}

/** Build a `Transcript` from raw caption segments. For tests, the CLI, and demos without Ingestion. */
export function segmentsToTranscript(videoId: string, segments: readonly TranscriptSegment[], language?: Language): Transcript {
  const valid = parseTranscript(segments);
  const sentences = toTimedSentences(valid, language ?? detectLanguage(valid));
  return {
    videoId,
    sentences: sentences.map((s) => ({ id: `${videoId}-${s.index}`, text: s.text, startSeconds: s.start, endSeconds: s.end })),
  };
}
